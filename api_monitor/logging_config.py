"""Structured JSON logging with redaction and daily rotation.

Log records are emitted as one JSON object per line. Context fields are passed
through :func:`log_event`. Every string value is scrubbed for secrets (values
registered by :mod:`secrets_resolver`), bearer/basic credentials and long digit
sequences (account/card numbers) before it reaches a handler.
"""
from __future__ import annotations

import datetime as _dt
import json
import logging
import logging.handlers
import os
import re
from typing import Any, Dict, Mapping, Optional

from secrets_resolver import REGISTRY

ROOT_LOGGER = "apimon"
EVENTS_LOGGER = "apimon.events"
MAIN_LOG_FILE = "monitor.log"
EVENTS_LOG_FILE = "events.log"

SENSITIVE_KEY_RE = re.compile(
    r"(passw|secret|token|authori[sz]ation|api[-_]?key|cookie|credential|pin\b|cvv|"
    r"\bpan\b|account[-_]?(no|num)|card[-_]?(no|num)|iban|ssn|national[-_]?id)",
    re.IGNORECASE,
)
# Keys whose values are generated by the monitor itself and are safe to log verbatim.
SAFE_KEYS = frozenset(
    {
        "ts", "level", "logger", "event", "service_id", "execution_id", "environment",
        "state", "previous_state", "failure_reason", "notification_status", "alert_id",
        "incident_id", "validation_outcome", "event_type", "trigger", "config_path",
    }
)
_PATTERNS = [
    (re.compile(r"(?i)\b(bearer|basic)\s+[A-Za-z0-9._~+/=-]{6,}"), r"\1 ***"),
    (re.compile(r"(?i)\b(password|passwd|pwd|token|secret|api[-_]?key)\s*[=:]\s*[^\s,;&\"']+"), r"\1=***"),
    # 8+ consecutive digits (account / card / customer numbers): keep the last 4.
    (re.compile(r"(?<!\d)(\d{4,})(\d{4})(?!\d)"), lambda m: "*" * len(m.group(1)) + m.group(2)),
]
_RESERVED = set(vars(logging.LogRecord("x", 0, "x", 0, "", None, None)).keys()) | {"message", "asctime"}


def mask_text(text: str) -> str:
    """Remove secrets and sensitive-looking identifiers from free text."""
    if not text:
        return text
    for secret in REGISTRY.values():
        if secret in text:
            text = text.replace(secret, "***")
    for pattern, repl in _PATTERNS:
        text = pattern.sub(repl, text)  # type: ignore[arg-type]
    return text


def sanitize(value: Any, key: str = "", depth: int = 0) -> Any:
    """Recursively sanitize a value destined for a log record."""
    if depth > 6:
        return "<truncated>"
    if key and key not in SAFE_KEYS and SENSITIVE_KEY_RE.search(key):
        return "***"
    if isinstance(value, str):
        return value if key in SAFE_KEYS else mask_text(value)
    if isinstance(value, Mapping):
        return {str(k): sanitize(v, str(k), depth + 1) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [sanitize(v, key, depth + 1) for v in list(value)[:50]]
    if isinstance(value, (int, float, bool)) or value is None:
        return value
    return mask_text(str(value))


class JsonFormatter(logging.Formatter):
    def __init__(self, environment: str = "") -> None:
        super().__init__()
        self.environment = environment

    def format(self, record: logging.LogRecord) -> str:
        payload: Dict[str, Any] = {
            "ts": _dt.datetime.fromtimestamp(record.created, _dt.timezone.utc)
            .isoformat(timespec="milliseconds")
            .replace("+00:00", "Z"),
            "level": record.levelname,
            "logger": record.name,
            "event": mask_text(record.getMessage()),
        }
        if self.environment:
            payload["environment"] = self.environment
        ctx = getattr(record, "ctx", None)
        if isinstance(ctx, Mapping):
            for key, val in ctx.items():
                if key not in payload:
                    payload[key] = sanitize(val, key)
        for key, val in record.__dict__.items():
            if key not in _RESERVED and key != "ctx" and key not in payload:
                payload[key] = sanitize(val, key)
        if record.exc_info:
            # Exception type and sanitized message only; tracebacks may embed request data.
            exc_type, exc_value = record.exc_info[0], record.exc_info[1]
            payload["exception"] = {
                "type": exc_type.__name__ if exc_type else "Exception",
                "message": mask_text(str(exc_value))[:500],
            }
            if record.levelno >= logging.ERROR:
                payload["traceback"] = mask_text(self.formatException(record.exc_info))[-4000:]
        return json.dumps(payload, ensure_ascii=False, default=str)


def log_event(logger: logging.Logger, level: int, event: str, **fields: Any) -> None:
    """Emit a structured event. ``fields`` become top-level JSON keys."""
    logger.log(level, event, extra={"ctx": fields})


def get_logger(name: str = "") -> logging.Logger:
    return logging.getLogger(f"{ROOT_LOGGER}.{name}" if name else ROOT_LOGGER)


def get_events_logger() -> logging.Logger:
    return logging.getLogger(EVENTS_LOGGER)


def _file_handler(path: str, retention_days: int, formatter: logging.Formatter) -> logging.Handler:
    handler = logging.handlers.TimedRotatingFileHandler(
        path, when="midnight", interval=1, backupCount=max(1, retention_days),
        encoding="utf-8", delay=True, utc=True,
    )
    handler.setFormatter(formatter)
    return handler


def setup_logging(log_cfg: Mapping[str, Any], environment: str, *, console_override: Optional[bool] = None) -> None:
    """(Re)configure logging. Safe to call more than once."""
    level = getattr(logging, str(log_cfg.get("level", "INFO")).upper(), logging.INFO)
    formatter = JsonFormatter(environment)
    root = logging.getLogger(ROOT_LOGGER)
    events = logging.getLogger(EVENTS_LOGGER)
    for logger in (root, events):
        for handler in list(logger.handlers):
            logger.removeHandler(handler)
            handler.close()
    root.setLevel(level)
    root.propagate = False
    events.setLevel(logging.INFO)
    events.propagate = True  # event history also appears in the main log

    directory = log_cfg.get("directory")
    if directory:
        os.makedirs(directory, mode=0o750, exist_ok=True)
        retention = int(log_cfg.get("retention_days", 30))
        root.addHandler(_file_handler(os.path.join(directory, MAIN_LOG_FILE), retention, formatter))
        events_retention = int(log_cfg.get("event_history_retention_days", max(retention, 90)))
        events.addHandler(_file_handler(os.path.join(directory, EVENTS_LOG_FILE), events_retention, formatter))

    console = log_cfg.get("console", False) if console_override is None else console_override
    if console or not directory:
        stream = logging.StreamHandler()
        stream.setFormatter(formatter)
        root.addHandler(stream)


def set_level(level_name: str) -> None:
    logging.getLogger(ROOT_LOGGER).setLevel(getattr(logging, level_name.upper(), logging.INFO))


# Library default: silent until setup_logging() is called.
logging.getLogger(ROOT_LOGGER).addHandler(logging.NullHandler())
